/** Get options for a data source, or return inline options */
export function getFieldOptions(
  dataSource: DataSourceId | undefined,
  inlineOptions: string[] | undefined,
): string[] {
  if (dataSource && dataSource !== 'custom' && dataSources[dataSource]) {
    return dataSources[dataSource];
  }
  return inlineOptions ?? [];
}

/** Check if a data source is a known named source */
export function isKnownDataSource(source: string | undefined): source is Exclude<DataSourceId, 'custom'> {
  return !!source && source !== 'custom' && source in dataSources;
}
